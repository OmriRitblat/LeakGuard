"""The Secret aggregate (ADD 5.2.5)."""

from __future__ import annotations

from dataclasses import dataclass, field
from datetime import datetime
from enum import Enum
from uuid import UUID

from leakguard.domain.common.enums import Label


class SecretStatus(Enum):
    """Secret.status. Removal is a soft delete, so the identifier stays permanent (INV-02)."""

    ACTIVE = "ACTIVE"
    REMOVED = "REMOVED"


class ExampleSource(Enum):
    """LabeledExample.source: who produced the example."""

    ADMIN = "ADMIN"          # written by the admin when creating the secret (FR-13)
    GENERATED = "GENERATED"  # generated by the local LLM (FR-16)
    VERIFIED = "VERIFIED"    # a verification case the admin labelled (FR-17, FR-18)


class Split(Enum):
    """LabeledExample.split. EVAL examples are never indexed or calibrated on (NFR-14)."""

    TRAIN = "TRAIN"
    EVAL = "EVAL"


@dataclass
class ExposurePolicy:
    """What counts as exposing the secret and what may be said about it (FR-14).

    Each prohibited detail is indexed in the VectorIndex with kind POLICY_DETAIL.
    """

    prohibited_details: list[str] = field(default_factory=list)
    permitted_descriptions: list[str] = field(default_factory=list)


@dataclass
class ViewPermission:
    """A user allowed to view the secret's details (FR-15, FR-24)."""

    user_id: UUID
    granted_at: datetime


@dataclass
class LabeledExample:
    """One labelled prompt of a secret (FR-13, FR-16, FR-18).

    Roles:
      - TRAIN + EXPOSURE: indexed next to the description and prohibited details;
      - TRAIN + NON_EXPOSURE: used only to calibrate thresholds;
      - EVAL: kept apart to measure precision and recall (NFR-14).

    Invariants:
      - IndexedOnlyTrainExposure: in the VectorIndex implies split = TRAIN and label = EXPOSURE;
      - VerifiedIsTrain: source = VERIFIED implies split = TRAIN.
    """

    id: UUID
    secret_id: UUID
    text: str  # encrypted at rest
    label: Label
    source: ExampleSource
    split: Split


@dataclass
class Secret:
    """«aggregate root» Secret.

    Invariants:
      - PermanentId: ids are unique and a removed secret keeps its id (INV-02);
      - UniqueCode: codes are unique;
      - Thresholds: 0 <= pass_threshold < block_threshold <= 1;
      - CeRange: 0 <= ce_threshold <= 1;
      - OnePermissionPerUser: permissions are unique by user_id;
      - RemovedHasNoViewers: status = REMOVED implies permissions is empty (UC-06 step 4);
      - BothLabels: status = ACTIVE implies examples hold both EXPOSURE and NON_EXPOSURE;
      - OwnExamples: every example has secret_id = id.

    Hint: examples are loaded lazily; SecretRepository.get(id) may return the
    secret without them, and list_examples reads them on demand.
    """

    id: UUID
    code: str
    name: str  # encrypted at rest
    description: str  # encrypted at rest
    pass_threshold: float
    block_threshold: float
    ce_threshold: float
    status: SecretStatus
    policy: ExposurePolicy
    permissions: list[ViewPermission] = field(default_factory=list)
    examples: list[LabeledExample] = field(default_factory=list)


@dataclass(frozen=True)
class ExampleDraft:
    """«value object» One example the admin writes in a SecretDraft. Not in diagram v11."""

    text: str
    label: Label


@dataclass(frozen=True)
class SecretDraft:
    """«value object» The admin's input to SecretService.create (UC-03). Not in diagram v11.

    Pre-conditions checked by create: name and description not empty; at least one
    EXPOSURE and one NON_EXPOSURE example.
    """

    code: str
    name: str
    description: str
    policy: ExposurePolicy
    examples: tuple[ExampleDraft, ...]
